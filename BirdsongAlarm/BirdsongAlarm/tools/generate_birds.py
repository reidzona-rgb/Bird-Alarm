def slugify(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    # 1. Patch existing birds
    patched = 0
    for folder_name, patch in PATCHES.items():
        path = os.path.join(ROOT, folder_name, "metadata.json")
        if not os.path.exists(path):
            print(f"  MISSING {folder_name}/metadata.json — skipping patch")
            continue
        with open(path, encoding="utf-8") as f:
            meta = json.load(f)
        changed = False
        for k, v in patch.items():
            if meta.get(k) != v:
                meta[k] = v
                changed = True
        if changed:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(meta, f, indent=2, ensure_ascii=False)
                f.write("\n")
            patched += 1
    print(f"Patched {patched} existing birds.")

    # 2. Number new birds starting after existing folders
    existing = sorted(d for d in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, d)))
    next_num = max((int(d[:2]) for d in existing if d[:2].isdigit()), default=0) + 1

    seen_slugs = set()
    created = 0
    for entry in NEW_BIRDS:
        name, sci, region, score, f1, f2, f3 = entry
        if score == 0:  # skip/duplicate placeholder entries
            continue
        slug = slugify(name)
        if slug in seen_slugs:
            print(f"  DUPLICATE slug '{slug}' for '{name}' — skipping")
            continue
        seen_slugs.add(slug)
        folder_name = f"{next_num:02d}_{slug}"
        folder = os.path.join(ROOT, folder_name)
        if os.path.exists(folder) and not args.force:
            next_num += 1
            continue
        os.makedirs(folder, exist_ok=True)
        meta = {
            "name": name,
            "scientific_name": sci,
            "region": region,
            "harmonic_score": score,
            "facts": [f1, f2, f3],
        }
        with open(os.path.join(folder, "metadata.json"), "w", encoding="utf-8") as f:
            json.dump(meta, f, indent=2, ensure_ascii=False)
            f.write("\n")
        next_num += 1
        created += 1

    print(f"Created {created} new bird folders.")
    print("Done. Run fetch_assets.py (or push to GitHub) to download audio and images.")

if __name__ == "__main__":
    main()
